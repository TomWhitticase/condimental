#!/usr/bin/env bash
# The project's own rules, checked mechanically.
#
# This repo is built mostly by agents in separate worktrees over sessions that
# do not share memory (docs/WORKFLOW.md, "GitHub"). The rules in CLAUDE.md and
# the footguns in .claude/skills/verify/SKILL.md are therefore re-learned from
# scratch every session — and the expensive ones are exactly those that fail
# SILENTLY: a Godot test script nobody wired into the runner still exits 0, a
# scene pointing at a deleted model still loads, a doc link to a renamed file
# still looks like a link. Every check below is one of those.
#
# What is NOT here, deliberately:
#   - "gameplay logic lives in Rust" and "content is data" (CLAUDE.md) cannot
#     be grepped for without lying about it. Review catches those.
#   - data/*.ron parsing. Those files are `include_str!`ed into sim_core, so
#     `cargo test -p sim_core` already fails on a malformed one.
#
# Usage: scripts/check-invariants.sh   (seconds, needs nothing but bash/git)

set -uo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$repo_root" || exit 1

status=0
fail() { echo "FAIL: $*" >&2; status=1; }

# ---------------------------------------------------------------- 1. tests
# SKILL.md gotcha 1: "A new test script must print a marker and be added to
# verify-core-loop.sh's run_godot_script list, or it is not being run." Godot
# exits 0 on a script it never loaded, so a forgotten one is invisible.
echo "==> every godot_project/test_*.gd is actually run by something"
for path in godot_project/test_*.gd; do
  name="$(basename "$path")"
  grep -qrF "$name" scripts/ \
    || fail "$name is run by no script in scripts/ — add it to verify-core-loop.sh's run_godot_script list (or to whichever runner owns it)"
done

echo "==> every run_godot_script marker is one its script actually prints"
# The marker IS the proof the script ran; a typo in either half turns the
# whole test into a no-op that passes.
while read -r script marker; do
  [ -f "godot_project/$script" ] || { fail "verify-core-loop.sh runs godot_project/$script, which does not exist"; continue; }
  grep -qwF "$marker" "godot_project/$script" \
    || fail "verify-core-loop.sh greps $script for '$marker', which $script never prints"
done < <(sed -n 's/^run_godot_script \([a-z_0-9]*\.gd\) \([A-Z_0-9]*\).*/\1 \2/p' scripts/verify-core-loop.sh)

# ------------------------------------------------------------- 2. scenes
# CLAUDE.md: "Scenes stay text .tscn/.tres. Never binary, no visual
# scripting." Godot will happily write .scn/.res if someone saves from the
# editor with the wrong extension, and a binary scene is unreviewable and
# unmergeable — the whole reason for the rule.
echo "==> scenes and resources are text, not binary"
while read -r f; do
  [ -n "$f" ] && fail "$f is a binary Godot scene/resource — save it as .tscn/.tres (CLAUDE.md)"
done < <(git ls-files '*.scn' '*.res')

while read -r f; do
  head -c 4 "$f" | grep -q '^\[gd' \
    || fail "$f does not start with a [gd_…] header — is it really a text scene? (CLAUDE.md)"
done < <(git ls-files '*.tscn' '*.tres')

# --------------------------------------------------------- 3. res:// paths
# SKILL.md gotcha 5: "A headless test cannot catch a stale content-id lookup.
# Structural tests pass while the scene renders nothing, because the lookup
# falls back." A path typo'd or left behind by a rename is the cheap half of
# that class of bug, and grep does catch it.
#
# Only paths with a committed asset extension are checked: res://voxels/*.vox
# is generated by `cargo xtask` into a gitignored directory, and a path built
# with a format specifier ("res://voxels/%s.vox") is not a path at all. A
# deliberately-bad path in a negative test says so with `ci-allow-missing`.
echo "==> every res:// path in a .gd/.tscn points at a file that exists"
while read -r path; do
  [ -e "godot_project/${path#res://}" ] \
    || fail "res:// path does not exist: $path"
done < <(grep -rhoE '"res://[^"%]+\.(tscn|tres|gd|png|svg|ogg|wav|gdextension|import)"' \
           godot_project --include='*.gd' --include='*.tscn' \
         | grep -v ci-allow-missing | tr -d '"' | sort -u)

# -------------------------------------------------------- 4. hover flags
# The screenshot harness is the one check that needs a window, so none of it
# runs in CI — and a `--hover*` flag that cannot find its target used to aim
# at nothing, photograph the parked cursor and report success (PR #78's
# re-review). The refusal now lives in ONE loop over `hover_targets.gd`'s
# table, which only holds if nothing else in test_screenshot.gd parses a
# hover flag of its own. An eighth one added the old way — a `_hover_x`
# boolean beside the rest — would be invisible to `test_hover_targets.gd`,
# which only knows what is in the table.
echo "==> every --hover* flag test_screenshot.gd knows about is in the table"
# Either quote: GDScript takes both, so a flag written args.has('--hover-belt')
# must not slip past a pattern that only knows about double quotes.
while read -r flag; do
  grep -qE "[\"']${flag}[\"']" godot_project/hover_targets.gd \
    || fail "test_screenshot.gd names $flag, which hover_targets.gd's table does not — add a row there instead, so the flag inherits the refusal (see that file's header)"
done < <(grep -ohE "[\"']--hover[a-z-]*[\"']" godot_project/test_screenshot.gd \
         | tr -d "\"'" | sort -u)

# --------------------------------------------------- 5. the pinned clock
# A review render is only reproducible because `screenshot-scene.sh` passes
# `--fixed-fps` (issue #82), and `test_screenshot.gd` refuses a run whose
# frames did not arrive at that rate. Two halves, in two languages, that
# have to agree on one number: drop the flag and every shot silently goes
# back to being a function of the host's load, raise it in one place only
# and every shot refuses. Neither failure can be caught by the headless
# suite, because nothing headless renders.
echo "==> screenshot-scene.sh pins the frame clock test_screenshot.gd insists on"
sh_fps="$(grep -oE '^fixed_fps=[0-9]+' scripts/screenshot-scene.sh | head -1 | cut -d= -f2)"
gd_fps="$(grep -oE '^const FIXED_FPS := [0-9]+' godot_project/test_screenshot.gd | head -1 | grep -oE '[0-9]+')"
if [ -z "$sh_fps" ]; then
  fail "scripts/screenshot-scene.sh sets no fixed_fps — without --fixed-fps a render is not reproducible (issue #82)"
elif ! grep -qE '^[[:space:]]*--fixed-fps ' scripts/screenshot-scene.sh; then
  fail "scripts/screenshot-scene.sh sets fixed_fps=$sh_fps but does not pass --fixed-fps to godot (issue #82)"
elif [ -z "$gd_fps" ]; then
  fail "godot_project/test_screenshot.gd declares no FIXED_FPS to check the harness's clock against (issue #82)"
elif [ "$sh_fps" != "$gd_fps" ]; then
  fail "screenshot-scene.sh renders at $sh_fps fps and test_screenshot.gd insists on $gd_fps — every shot would refuse"
fi

# ----------------------------------------------------------- 6. doc links
# The docs are the project's memory and CLAUDE.md is a map of them
# (docs/WORKFLOW.md, "Recording a decision"). A link into a renamed or moved
# file breaks the map quietly — nothing fails, the next session just does not
# find the reasoning and re-litigates a settled decision.
echo "==> the review render seals the camera against the machine it runs on"
# The other half of issue #82: a render aims the camera and then runs frames,
# and those frames poll the real keyboard and see the real mouse. main.gd's
# guard is covered headlessly by test_camera_seal.gd; that the RENDER actually
# turns it on is not, because nothing headless renders.
if ! grep -q "_camera_input_sealed" godot_project/main.gd; then
  fail "godot_project/main.gd has no _camera_input_sealed — live input can move a review render's camera (issue #82)"
fi
if ! grep -qE "_camera_input_sealed = true" godot_project/test_screenshot.gd; then
  fail "godot_project/test_screenshot.gd never seals the camera — a held key or a stray wheel notch can move the shot between the aim and the shutter (issue #82)"
fi

echo "==> the tech debt total is the sum of its items, item numbers unique"
# A silent merge of two edits to docs/TECH_DEBT.md's total is otherwise
# invisible, and that total is what the feature freeze reads.
scripts/tech-debt-status.sh --check || status=1

echo "==> every relative link between markdown files resolves"
while read -r src link; do
  target="$(dirname "$src")/${link}"
  [ -e "$target" ] || fail "$src links to $link, which does not exist"
done < <(
  git ls-files '*.md' | while read -r md; do
    grep -oE '\]\([^):#]+\.md(#[^)]*)?\)' "$md" 2>/dev/null \
      | sed -E 's/^\]\(//; s/(#[^)]*)?\)$//' \
      | while read -r link; do printf '%s %s\n' "$md" "$link"; done
  done
)

echo
if [ "$status" -eq 0 ]; then
  echo "PASS: test scripts wired and marked, scenes text, res:// paths real, hover flags tabled, review clock pinned and camera sealed, debt total adds up, doc links resolve"
else
  echo "FAILED — see above" >&2
fi
exit $status
